-- ============================================================================
-- 013_add_superseded_by.sql
-- ============================================================================
-- 目的     ：让「重新生成 / 重新回答」成为**一等公民** —— 同一个问题可以有多个回答版本，
--            但只有当前生效的那版进模型上下文，被替代的版本只留给前端做 n/n 切换显示。
-- 影响表   ：chat_memory（加 1 列 + 1 个索引）。
-- 幂等性   ：可重放（ADD COLUMN IF NOT EXISTS / CREATE INDEX IF NOT EXISTS）。
-- 破坏性   ：无，只加**可空**列，不改写既有数据。
-- 回滚     ：
--   DROP INDEX  IF EXISTS "public"."idx_chat_memory_session_active";
--   ALTER TABLE "public"."chat_memory" DROP COLUMN IF EXISTS "superseded_by";
-- 执行方式 ：
--   psql -h <SERVICE_IP> -U <DB_USERNAME> -d nexus_agent -f docs/sql/013_add_superseded_by.sql
--
-- ---------------------------------------------------------------------------
-- 背景：为什么只是「前端折叠一下」不够
-- ---------------------------------------------------------------------------
-- 用户点「重新生成」后，库里会多出一组消息。前端把它显示成「问题A → 回答A」
-- 与「问题A → 回答B」两轮独立对话（用户反馈的原始现象）。
--
-- 但**真正的问题在服务端**：PgChatMemoryStore.getMessages() 每轮都把
-- **全量历史**反序列化成 LangChain4j 的记忆，于是模型上下文变成：
--
--     问：问题A
--     答：回答A
--     问：问题A
--     答：回答B        ← 回答A 也还在里面
--
-- 三个后果：
--   1. 白烧 token —— 两个回答都进上下文，直接踩「首字延迟」这条线；
--   2. 模型困惑 —— 同一问题问了两遍、答了两遍，容易重复啰嗦；
--   3. 前端做 n/n 切换**形同虚设** —— 用户切回 1/2 接着聊，模型上下文里
--      2/2 的内容一个字没少。
--
-- 所以需要一个**可持久化的标记**，告诉服务端「这条回答已被更新的一版替代」，
-- 记忆加载时把它排除掉。进程内标记做不到（刷新一次就丢），必须落库。
--
-- ---------------------------------------------------------------------------
-- 为什么存 superseded_by（指向替代者）而不是 regenerate_of（指向被替代者）
-- ---------------------------------------------------------------------------
-- 两种方向都能表达同一关系，选前者有两个实际好处：
--   1. **「当前生效」是天然可查的**：`superseded_by IS NULL` 即当前版本。
--      若用后者，要写成 `NOT EXISTS(SELECT 1 ... WHERE regenerate_of = m.id)`，
--      每次读历史多一层子查询，且语义不如前者直观。
--   2. **历史接口天然能直接返回**：前端要回答「这条是不是过期了」，
--      直接读本列即可，不用在应用层再推一遍关系。
--
-- ---------------------------------------------------------------------------
-- 语义约定
-- ---------------------------------------------------------------------------
-- · 只有 **AI 回答** 会有 superseded_by；用户提问永远为 NULL。
-- · 前端传 regenerateFromMessageId（要基于哪条回答重新生成）时，
--   服务端会把「比它新的、尚未被替代的 AI 回答」全部标记为被这条新回答替代。
--   → 于是「切回旧版本再重新生成」也能正确工作：更新的那些自动出局。
-- · 被替代的行**仍然保留**，只是不进模型上下文 —— 前端要做 n/n 切换就得看得到它们。
--
-- ---------------------------------------------------------------------------
-- 向后兼容
-- ---------------------------------------------------------------------------
-- 新列可空：不带本参数发起的普通对话（用户第一次发问）不会写这一列，
-- 历史行为 NULL = 当前版本，行为与本脚本执行前完全一致。
-- 本脚本之前的历史数据同样为 NULL，不会被任何一次查询排除掉。

ALTER TABLE "public"."chat_memory"
    ADD COLUMN IF NOT EXISTS "superseded_by" bigint;

COMMENT ON COLUMN "public"."chat_memory"."superseded_by" IS
    '若非空 = 这条 AI 回答已被另一条更新的回答替代（存替代者的 chat_memory.id）。'
    '记忆加载（getActiveForChat）会排除这些行，避免同一问题的多个版本同时进模型上下文；'
    '历史接口仍全部返回，供前端做 n/n 版本切换。NULL = 当前生效的版本。';

-- ---------------------------------------------------------------------------
-- 索引：这一次**确实**有服务端查询，值得加
-- ---------------------------------------------------------------------------
-- 与 docs/sql/011 的 run_id 不同，superseded_by 是**服务端要用的**：
--   记忆加载每轮都执行 `WHERE session_id=? AND user_id=? AND superseded_by IS NULL`，
--   是本项目最热的读路径之一（每一次对话请求都走）。
-- 没有索引时，PostgreSQL 只能按 session_id 的既有索引过滤后再逐行判空；
-- 长会话（几百上千行）下这笔开销会随会话变长而增长。
CREATE INDEX IF NOT EXISTS "idx_chat_memory_session_active"
    ON "public"."chat_memory" (session_id, user_id)
    WHERE superseded_by IS NULL;

