-- ============================================================================
-- 5. 索引
-- ============================================================================
-- 每一条都对应代码里真实出现的查询条件（附出处），不做无依据的加索引。

-- 会话消息：所有历史读取都按 session_id 过滤
--   ChatMemoryMapper.getAllByMemoryId / getAllByMemoryIdAndUserId / getCountByMemoryId
CREATE INDEX idx_chat_memory_session_id ON "public"."chat_memory" ("session_id");
-- 越权修复后，对外读历史同时过滤 user_id
CREATE INDEX idx_chat_memory_user_id    ON "public"."chat_memory" ("user_id");

-- 会话列表：ChatHistoryListServiceImpl.getList → where user_id order by update_time desc
CREATE INDEX idx_chat_history_list_user_upd
  ON "public"."chat_history_list" ("user_id", "update_time" DESC);

-- 长期记忆：UserMemoryServiceImpl.getMemory → where user_id (+ content LIKE)
CREATE INDEX idx_user_memory_user_id ON "public"."user_memory" ("user_id");

-- 上传文件：FileServiceImpl.getFileByUserId → where user_id (+ biz_type, file_name LIKE)
CREATE INDEX idx_sys_file_user_biz ON "public"."sys_file" ("user_id", "biz_type");

-- 知识库：KnowledgeBaseServiceImpl.getKnowledgeList → where user_id
CREATE INDEX idx_knowledge_base_user_id ON "public"."knowledge_base" ("user_id");

-- MCP：McpInformationServiceImpl.getMcp → where user_id and id in (...)
--      （user_id 上的索引；唯一约束 uk_mcp_user_strid 已覆盖 (user_id, str_id)）
CREATE INDEX idx_mcp_information_user_id ON "public"."mcp_information" ("user_id");

-- 系统日志：按时间倒序查看
CREATE INDEX idx_system_log_create_at ON "public"."system_log" ("create_at" DESC);

-- 向量索引：PgVectorEmbeddingStore 的相似度检索用余弦距离（<=>），故用 vector_cosine_ops。
-- 这是 HNSW（近似最近邻），查询快、构建慢；知识库数据量很小时也可改用 ivfflat。
CREATE INDEX idx_knowledge_embedding_hnsw
  ON "public"."knowledge_embedding" USING hnsw ("embedding" vector_cosine_ops);


