-- 6. 未纳入本文件的已知问题（需要改代码，不是改表）
-- ============================================================================
-- 6.1 UserMemoryMapper.xml 的 search 语句是坏的：它 SELECT 了 user_memory 表中
--     并不存在的 category 与 embedding 两列。该方法是死代码（UserMemoryServiceImpl
--     .searchMemory 从未被调用，MemoryTool 走的是 LIKE 查询），所以暂时不报错，
--     但只要有人调用就会失败。→ 归入重构计划 P2-7（长期记忆检索方案）一起处理。
--
-- 6.2 User 实体缺少 @TableId：users.id 是主键，但实体上没有标注。
--     MyBatis-Plus 对「无主键实体」的 getById / updateById / removeById 会失败。
--     本文件已给出 users 主键，代码侧需补 @TableId（一行）。
--
-- 6.3 knowledge_base_file 的业务语义：知识库详情返回的文件列表实际取自
--     fileService.queryFileByids(...)（即 sys_file），表里的 file_name 目前只是冗余留存。
--     将来若确定不再需要，可考虑删列。
-- ============================================================================
